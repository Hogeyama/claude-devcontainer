"""Real overlay copy-up, whiteouts, pnpm links and container recreation."""
import importlib.util
import os
from pathlib import Path
import tempfile
import unittest
import uuid
from proxy_integration_test import docker

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('settings', ROOT / '.devcontainer/claude/scripts/settings.py')
settings = importlib.util.module_from_spec(spec)
spec.loader.exec_module(settings)
IMAGE = os.environ.get('AGENT_TEST_IMAGE', 'claude-devcontainer-agent:task2')


@unittest.skipUnless(os.environ.get('RUN_DOCKER_TESTS') == '1', 'Docker integration disabled; set RUN_DOCKER_TESTS=1')
class NodeModulesIntegrationTest(unittest.TestCase):
    def test_overlay_does_not_write_host_or_hardlink_store(self):
        temporary = tempfile.TemporaryDirectory(prefix='cdc-node-cow-')
        self.addCleanup(temporary.cleanup)
        root = Path(temporary.name)
        root.chmod(0o755)
        repo = root / 'repo'
        repo.mkdir()
        env = {'XDG_STATE_HOME': str(root / 'state')}
        # As agent.mounts = ["/workspace/node_modules:cow"] makes it.
        lower = repo / 'node_modules'
        lower.mkdir()
        paths = settings.cow_paths(str(lower), '/workspace/node_modules', repo, env)
        def prepare():
            for key in ('upper', 'work'):
                paths[key].mkdir(parents=True, exist_ok=True)
        prepare()
        store = root / 'store-file'
        store.write_text('host-store')
        os.link(store, lower / 'hardlinked')
        (lower / 'remove').write_text('host-remove')
        package = lower / '.pnpm/fixture/node_modules/fixture'
        package.mkdir(parents=True)
        (package / 'index.js').write_text('module.exports = 42;\n')
        (lower / 'fixture').symlink_to('.pnpm/fixture/node_modules/fixture')
        self.addCleanup(docker, 'run', '--rm', '--network', 'none', '--entrypoint', 'rm',
                        '-v', str(root / 'state') + ':/state', IMAGE,
                        '-rf', '/state/claude-devcontainer/cow')
        name = 'cdc-node-cow-' + uuid.uuid4().hex[:12]
        self.addCleanup(docker, 'volume', 'rm', name)
        options = f'lowerdir={lower},upperdir={paths["upper"]},workdir={paths["work"]}'
        docker('volume', 'create', '--driver', 'local', '--opt', 'type=overlay', '--opt', 'device=overlay', '--opt', 'o=' + options, name)
        workspace = name + '-workspace'
        self.addCleanup(docker, 'volume', 'rm', workspace)
        docker('volume', 'create', workspace)
        # Same UID as the host-owned upper, like the configured agent UID.
        def run(script):
            return docker('run', '--rm', '--network', 'none', '--user', f'{os.getuid()}:{os.getgid()}',
                          '--cap-drop', 'ALL', '--entrypoint', 'sh',
                          '--mount', f'type=volume,src={name},dst=/deps,volume-nocopy',
                          '--mount', f'type=volume,src={workspace},dst=/workspace', IMAGE, '-ec', script)
        self.assertEqual(run("cd /deps; node -e \"console.log(require('./fixture'))\"; "
                             "echo agent > hardlinked; rm remove; echo new > added; echo unfinished > /workspace/untracked" ).splitlines()[0], '42')
        self.assertEqual(store.read_text(), 'host-store')
        self.assertEqual((lower / 'hardlinked').read_text(), 'host-store')
        self.assertEqual((lower / 'remove').read_text(), 'host-remove')
        self.assertFalse((lower / 'added').exists())
        self.assertEqual(run('cat /deps/hardlinked /deps/added; test ! -e /deps/remove'), 'agent\nnew\n')

        # All run --rm containers are gone: overlays are unmounted. Refresh
        # only Node's layers, leaving the independent workspace volume intact.
        (lower / 'remove').write_text('host-refreshed')
        layer_root = paths['upper'].parent
        docker('run', '--rm', '--network', 'none', '--entrypoint', 'rm',
               '-v', str(layer_root) + ':/layers', IMAGE, '-rf', '/layers/upper', '/layers/work')
        prepare()
        self.assertEqual(run('cat /deps/remove; test ! -e /deps/added'), 'host-refreshed')
        self.assertEqual(run('cat /deps/hardlinked /workspace/untracked'), 'host-storeunfinished\n')
